const letterSec = document.getElementById("ch23");
if (letterSec && !reduced) {
  const lLines = [...letterSec.querySelectorAll(".line")];
  const caret = document.createElement("span");
  caret.className = "type-caret";
  let lStarted = false;
  const startLetter = () => {
    if (lStarted) return;
    lStarted = true;
    lLines.forEach((l) => {
      l.dataset.orig = l.textContent;
      l.textContent = "";
    });
    const typeLine = (li) => {
      if (li >= lLines.length) {
        if (caret.isConnected) caret.remove();
        return;
      }
      const line = lLines[li];
      const text = line.dataset.orig;
      line.appendChild(caret);
      let ci = 0;
      const step = () => {
        if (!lStarted || !line.isConnected) return;
        if (ci < text.length) {
          line.insertBefore(document.createTextNode(text.charAt(ci++)), caret);
          setTimeout(step, 18 + Math.random() * 34);
        } else {
          setTimeout(() => typeLine(li + 1), 240);
        }
      };
      step();
    };
    typeLine(0);
  };
  const lio = new IntersectionObserver(
    (es) => {
      if (es.some((e) => e.isIntersecting)) {
        startLetter();
        lio.disconnect();
      }
    },
    { threshold: 0.18 }
  );
  lio.observe(letterSec);
}

