function buildChapter(ch, chIndex) {
  const sec = document.createElement("section");
  sec.className =
    "screen" +
    (ch.type ? " screen-" + ch.type : "") +
    (chIndex === 0 ? " screen-first" : "");
  sec.id = ch.id;
  sec.dataset.num = ch.id === "ch23" ? "♥" : pad2(chIndex + 1);
  sec.dataset.ch = chIndex + 1;

  const eb = document.createElement("p");
  eb.className = "chapter";
  eb.textContent = ch.eyebrow;
  sec.appendChild(eb);

  const h2 = document.createElement("h2");
  h2.className =
    "screen-title" +
    (ch.titleHTML ? "" : ch.cold ? " cold" : " warm") +
    (chIndex === 0 ? " hero" : "");
  if (ch.titleHTML) h2.innerHTML = ch.titleHTML;
  else h2.textContent = ch.title;
  sec.appendChild(h2);

  if (ch.sub) {
    const sp = document.createElement("p");
    sp.className = "section-sub";
    sp.textContent = ch.sub;
    sec.appendChild(sp);
  }

  if (ch.type === "compare") {
    /* две карточки: до тебя / с тобой — как в первом сайте */
    const grid = document.createElement("div");
    grid.className = "ba-grid";

    const cardB = document.createElement("div");
    cardB.className = "ba-card ba-before-card";
    cardB.innerHTML =
      '<div class="ba-head"><span class="ba-icon">🌒</span><h3>до тебя</h3></div><ul></ul>';
    const cardA = document.createElement("div");
    cardA.className = "ba-card ba-after-card";
    cardA.innerHTML =
      '<div class="ba-head"><span class="ba-icon">☀️</span><h3>с тобой</h3></div><ul></ul>';

    ch.pairs.forEach(([b, a], i) => {
      const li1 = document.createElement("li");
      li1.textContent = b;
      li1.style.setProperty("--i", i);
      const li2 = document.createElement("li");
      li2.textContent = a;
      li2.style.setProperty("--i", i);
      cardB.querySelector("ul").appendChild(li1);
      cardA.querySelector("ul").appendChild(li2);
    });

    const arrow = document.createElement("div");
    arrow.className = "ba-arrow";
    arrow.setAttribute("aria-hidden", "true");
    arrow.innerHTML = "<span>⟶</span>";

    grid.append(cardB, arrow, cardA);
    sec.appendChild(grid);
  } else if (ch.type === "langs") {
    const grid = document.createElement("div");
    grid.className = "langs-grid";
    const rots = [-1.8, 1.4, -1.1, 2.0, -1.5, 1.0, -2.2, 1.7];
    LANGS.forEach((lg, i) => {
      const card = document.createElement("div");
      card.className = "lang-card";
      card.style.setProperty("--rot", rots[i % rots.length] + "deg");
      card.style.transitionDelay = Math.min(i * 35, 1500) + "ms";
      const f = document.createElement("span");
      f.className = "lang-flag";
      f.textContent = lg.flag;
      const p = document.createElement("p");
      p.className = "lang-phrase";
      p.textContent = lg.phrase;
      const nm = document.createElement("p");
      nm.className = "lang-name";
      nm.textContent = lg.name;
      card.append(f, p, nm);
      grid.appendChild(card);
      if (!reduced) {
        let lastBurst = 0;
        card.addEventListener("mouseenter", () => {
          const t = performance.now();
          if (t - lastBurst < 1200) return;
          lastBurst = t;
          const r = card.getBoundingClientRect();
          heartBurst((r.left + r.width / 2) * DPR, r.top * DPR, 6, 0.5);
        });
      }
    });
    sec.appendChild(grid);
  } else if (ch.type === "orbit") {
    const sys = document.createElement("div");
    sys.className = "orbit-sys";
    sys.setAttribute("aria-hidden", "true");
    sys.innerHTML =
      '<div class="orbit-ring orbit-ring2"></div>' +
      '<div class="orbit-ring"></div>' +
      '<div class="orbit-sun">☀️</div>' +
      '<div class="orbit-moon"></div>' +
      '<div class="orbit-planet"></div>';
    sec.appendChild(sys);
    const wrap = document.createElement("div");
    wrap.className = "lines";
    ch.lines.forEach((ln) => wrap.appendChild(makeLine(ln)));
    if (wrap.lastElementChild) wrap.lastElementChild.dataset.chEnd = "1";
    sec.appendChild(wrap);
  } else if (ch.type === "promises") {
    const list = document.createElement("div");
    list.className = "prom-list";
    PROMISES.forEach((p, i) => {
      const row = document.createElement("div");
      row.className = "prom-row";
      row.style.setProperty("--i", i);
      const seal = document.createElement("span");
      seal.className = "prom-seal";
      seal.textContent = "♥";
      const tx = document.createElement("p");
      tx.className = "prom-text";
      tx.textContent = p;
      row.append(seal, tx);
      list.appendChild(row);
    });
    sec.appendChild(list);
  } else {
    const wrap = document.createElement("div");
    wrap.className = "lines";
    ch.lines.forEach((ln) => wrap.appendChild(makeLine(ln)));
    if (wrap.lastElementChild) wrap.lastElementChild.dataset.chEnd = "1";
    sec.appendChild(wrap);
  }

  if (chIndex === 0) {
    const hint = document.createElement("div");
    hint.className = "scroll-hint";
    hint.setAttribute("aria-hidden", "true");
    hint.innerHTML = '<span class="scroll-hint-mouse"></span><span>листай вниз</span>';
    sec.appendChild(hint);
  }

  return sec;
}

