const Audio = {
  ctx: null,
  master: null,
  playing: false,
  chordTimer: null,
  pluckTimer: null,
  chords: [
    [174.61, 220.0, 261.63, 329.63], // Fmaj7
    [164.81, 220.0, 261.63, 329.63], // Dm7
    [130.81, 196.0, 246.94, 293.66], // Cmaj7
    [146.83, 220.0, 293.66, 349.23], // Dm7/G
  ],
  pentatonic: [349.23, 392.0, 440.0, 523.25, 587.33],

  start() {
    if (this.playing) return;
    this.ctx = this.ctx || new (window.AudioContext || window.webkitAudioContext)();
    if (this.ctx.state === "suspended") this.ctx.resume();
    this.master = this.master || (() => {
      const g = this.ctx.createGain();
      g.gain.value = 0;
      g.connect(this.ctx.destination);
      return g;
    })();
    this.master.gain.linearRampToValueAtTime(0.45, this.ctx.currentTime + 3);
    this.playing = true;
    this.playChord(0);
    this.schedulePluck();
    $("#music-toggle").classList.add("playing");
  },

  stop() {
    this.playing = false;
    clearTimeout(this.chordTimer);
    clearTimeout(this.pluckTimer);
    if (this.master && this.ctx) {
      this.master.gain.linearRampToValueAtTime(0, this.ctx.currentTime + 1.2);
    }
    $("#music-toggle").classList.remove("playing");
  },

  playChord(idx) {
    if (!this.playing || !this.ctx) return;
    const t = this.ctx.currentTime;
    const chord = this.chords[idx % this.chords.length];
    const filter = this.ctx.createBiquadFilter();
    filter.type = "lowpass";
    filter.frequency.value = 900;
    filter.connect(this.master);
    chord.forEach((f, i) => {
      const osc = this.ctx.createOscillator();
      osc.type = i < 2 ? "sine" : "triangle";
      osc.frequency.value = f;
      const g = this.ctx.createGain();
      g.gain.setValueAtTime(0, t);
      g.gain.linearRampToValueAtTime(0.05, t + 3.2);
      g.gain.setValueAtTime(0.05, t + 6);
      g.gain.linearRampToValueAtTime(0, t + 11);
      osc.connect(g); g.connect(filter);
      osc.start(t); osc.stop(t + 11.5);
    });
    this.chordTimer = setTimeout(() => this.playChord(idx + 1), 8000);
  },

  schedulePluck() {
    if (!this.playing || !this.ctx) return;
    const t = this.ctx.currentTime;
    const f = this.pentatonic[Math.floor(rand(0, this.pentatonic.length))];
    const osc = this.ctx.createOscillator();
    osc.type = "sine";
    osc.frequency.value = f;
    const g = this.ctx.createGain();
    g.gain.setValueAtTime(0, t);
    g.gain.linearRampToValueAtTime(0.035, t + 0.03);
    g.gain.exponentialRampToValueAtTime(0.0001, t + 2.8);
    const pan = this.ctx.createStereoPanner();
    pan.pan.value = rand(-0.6, 0.6);
    osc.connect(g); g.connect(pan); pan.connect(this.master);
    osc.start(t); osc.stop(t + 3);
    this.pluckTimer = setTimeout(() => this.schedulePluck(), rand(1400, 2800));
  },
};

