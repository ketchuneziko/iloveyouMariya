function makeLine(obj) {
  const o = typeof obj === "string" ? { t: obj } : obj;
  const p = document.createElement("p");
  p.className =
    "line" +
    (o.em ? " em" : "") +
    (o.big ? " big" : "") +
    (o.mood ? " " + o.mood : "");
  p.textContent = o.t;
  if (o.final) p.dataset.final = "1";
  if (o.soft) p.dataset.soft = "1";
  return p;
}

function makeExtraHead(eyebrow, title, sub) {
  const eb = document.createElement("p");
  eb.className = "chapter";
  eb.textContent = eyebrow;
  const h2 = document.createElement("h2");
  h2.className = "screen-title warm";
  h2.textContent = title;
  const out = [eb, h2];
  if (sub) {
    const sp = document.createElement("p");
    sp.className = "section-sub";
    sp.textContent = sub;
    out.push(sp);
  }
  return out;
}

